fn expr_is_theme_color(expr: &Expr) -> bool {
    match expr {
        Expr::Member(base, _) => matches!(base.as_ref(), Expr::Ident(s) if s == "Theme"),
        Expr::Ternary {
            then_expr,
            else_expr,
            ..
        } => expr_is_theme_color(then_expr) || expr_is_theme_color(else_expr),
        _ => false,
    }
}

